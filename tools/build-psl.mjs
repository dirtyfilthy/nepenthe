#!/usr/bin/env node
// Converts a Public Suffix List (.dat) into src/psl-data.js.
// Usage: node tools/build-psl.mjs path/to/public_suffix_list.dat
// Get a fresh list from https://publicsuffix.org/list/public_suffix_list.dat
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) {
  console.error("usage: node tools/build-psl.mjs public_suffix_list.dat");
  process.exit(1);
}

const rules = [];
for (let line of readFileSync(src, "utf8").split("\n")) {
  line = line.trim().split(/\s/)[0];
  if (!line || line.startsWith("//")) continue;
  let prefix = "";
  if (line.startsWith("!")) { prefix = "!"; line = line.slice(1); }
  if (line.startsWith("*.")) { prefix += "*."; line = line.slice(2); }
  const ascii = domainToASCII(line);
  if (!ascii) throw new Error(`cannot convert rule: ${line}`);
  rules.push(prefix + ascii);
}

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "psl-data.js");
writeFileSync(
  out,
  "// Generated by tools/build-psl.mjs from the Public Suffix List\n" +
    "// (https://publicsuffix.org/), which is licensed under MPL-2.0.\n" +
    `// ${rules.length} rules. Do not edit by hand.\n` +
    `globalThis.PSL_RULES = ${JSON.stringify(rules.join("\n"))};\n`
);
console.log(`wrote ${rules.length} rules to ${out}`);
